import {readFile, writeFile} from 'node:fs/promises';

const adapter = await readFile(new URL('./character-builder-export.js', import.meta.url), 'utf8');
const output = `// Generated by tools/build-character-builder-console.mjs. Paste the entire file into the site's DevTools Console.
(async () => {
${adapter}
const json = window.D20FoundryExporter.toJSON();
window.d20FoundryJSON = json;
try {
    if (typeof copy === 'function') copy(json);
    else await navigator.clipboard.writeText(json);
    console.info('1d20 → Foundry: JSON скопійовано. Також доступний у window.d20FoundryJSON.');
} catch (error) {
    console.warn('JSON готовий, але буфер обміну недоступний. Виконайте copy(window.d20FoundryJSON) або D20FoundryExporter.download().', error);
}
return json;
})()
`;
await writeFile(new URL('./character-builder-console.js', import.meta.url), output, 'utf8');
console.log('Built tools/character-builder-console.js');
